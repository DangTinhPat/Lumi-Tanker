#!/usr/bin/env python3
"""Generate unit-mass inertials from watertight meshes; no density is inferred.

Requires numpy, trimesh and PyYAML only at generation/verification time.
Runtime Xacro multiplies these tensors by the supplied masses in masses.yaml.
"""

import argparse
import hashlib
from pathlib import Path

import numpy as np
import trimesh
import yaml


MODEL = Path(__file__).resolve().parents[1] / 'src/tap_robot_description/description/cad_robot'


def estimate(mesh_path):
    mesh = trimesh.load_mesh(mesh_path)
    if not mesh.is_watertight or not mesh.is_winding_consistent or mesh.volume <= 0:
        raise ValueError(f'{mesh_path}: expected a consistently wound closed solid')
    tensor = mesh.moment_inertia / mesh.volume
    moments = np.linalg.eigvalsh(tensor)
    if not np.isfinite(tensor).all() or moments[0] <= 0 or moments[2] > sum(moments[:2]) + 1e-12:
        raise ValueError(f'{mesh_path}: nonphysical inertia tensor')
    return {
        'mesh_sha256': hashlib.sha256(mesh_path.read_bytes()).hexdigest(),
        'center_of_mass': mesh.center_mass.tolist(),
        'inertia_per_kg': {
            name: float(tensor[i, j])
            for name, i, j in [('ixx', 0, 0), ('ixy', 0, 1), ('ixz', 0, 2),
                               ('iyy', 1, 1), ('iyz', 1, 2), ('izz', 2, 2)]
        },
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=MODEL / 'mesh_inertials.yaml')
    args = parser.parse_args()
    entries = {path.stem: estimate(path) for path in sorted((MODEL / 'meshes').glob('*.stl'))}
    if len(entries) != 7:
        raise ValueError('Expected seven meshes')
    header = ('# Generated by tools/estimate_inertials.py.\n'
              '# ESTIMATE: uniform solid density, not measured mass distribution.\n'
              '# COM: metres in link frame. Tensor: about COM, link-aligned axes, m^2.\n'
              '# Multiply inertia_per_kg by link mass in kg to obtain kg*m^2.\n')
    args.output.write_text(header + yaml.safe_dump(entries, sort_keys=False))
    print(f'Generated {len(entries)} unit-mass inertials: {args.output}')


if __name__ == '__main__':
    main()
