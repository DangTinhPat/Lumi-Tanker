#!/usr/bin/env python3
"""Derive fixed GIM shell/mount bounds directly from the original STEP.

Authoring only, cadquery-ocp required. Does not create/enable a simulator.
Uses the same assembly placements and CAD origin as gim_com_report.py.
"""
import argparse
import hashlib
import json
from pathlib import Path

from gim_com_report import ROOT, read_parts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'ROBOT (GIM6010-8).STEP')
    parser.add_argument('--header', type=Path, default=ROOT /
                        'src/tap_control/core/include/robot_control/GeneratedBodyEnvelope.hpp')
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    origin, parts = read_parts(args.source, with_bounds=True)
    # Fixed shell and exposed hip mounts. Battery is inside the shell; moving
    # it between internal slots does not change the external envelope.
    numbers = [7, 8, 31, 32, 50, 55]
    padding = 0.0001  # 0.1 mm numerical padding; not physical calibration.
    boxes = []
    for n in numbers:
        lo, hi = parts[n]['bounds_m']
        boxes.append(dict(component=n, name=parts[n]['name'],
                          lo=[v-padding for v in lo], hi=[v+padding for v in hi]))
    sha = hashlib.sha256(args.source.read_bytes()).hexdigest()
    lines = [
        '// Generated by tools/generate_body_envelope.py directly from GIM STEP solids.',
        f'// Source STEP SHA256: {sha}',
        '// +X forward, +Y left, +Z up; same assembly origin as PHYSICS.md.',
        '// Fixed shell/mount AABBs with 0.1 mm numerical padding, not calibrated contact.',
        '#pragma once', '#include <array>', 'namespace robot_control::geometry {',
        'struct BodyBox { std::array<float, 3> lo, hi; };',
        f'inline constexpr std::array<BodyBox, {len(boxes)}> body_envelope' + '{{']
    for box in boxes:
        lo = ', '.join(f'{v:.9f}F' for v in box['lo'])
        hi = ', '.join(f'{v:.9f}F' for v in box['hi'])
        lines.append('    {{' + lo + '}, {' + hi + '}},  // cad_' + str(box['component']))
    lines += ['}};', '}  // namespace robot_control::geometry', '']
    args.header.write_text('\n'.join(lines))
    report = dict(source=args.source.name, source_sha256=sha, cad_origin_mm=origin,
                  method='OpenCascade AddOptimal on placed STEP solids, no triangulation',
                  padding_m=padding, boxes=boxes,
                  limitations='Flat floor, encoder zero and IMU frame uncalibrated; excludes loose wiring and leg shells')
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(dict(source_sha256=sha, components=numbers, padding_m=padding,
                          header=str(args.header), report=str(args.report)), indent=2))


if __name__ == '__main__':
    main()
