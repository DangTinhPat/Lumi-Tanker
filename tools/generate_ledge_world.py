#!/usr/bin/env python3
"""Generate a ledge_test.sdf-style world at an arbitrary ledge height.

`src/tap_sim/worlds/ledge_test.sdf` hardcodes a 20 cm ledge; this generates
the same world (ground_plane + ledge_pad + departure fillet) parameterized
by height, for `tools/ledge_height_smoke.py`'s height sweep (see
docs/LEDGE_DRIVEOFF_LIMIT.md). Geometry relationships preserved exactly from
the hand-written 20 cm world:
  - ledge_pad box: size.z = height + 0.02 (buries 0.02 m under ground_plane's
    top so there is no floating-collision gap), pose.z = height/2 - 0.01.
  - departure fillet: radius fixed at 0.03 m (matches wheel radius), centered
    at (edge_x - r, height - r) so its surface is exactly tangent to both the
    pad's top and front face - true fillet, not an approximation.
  - Robot spawn_z = height + 0.2372 (0.2372 is the standard flat-ground
    wheel-ground offset, src/tap_sim/CONTRACT.md) - pass this to
    `sim.launch.py`'s spawn_z launch argument, it is not baked into the sdf.
"""
import argparse
from pathlib import Path

PAD_HALF_FOOTPRINT = 0.45  # 0.9 x 0.9 m pad, unchanged across heights
FILLET_RADIUS = 0.03
STANDARD_WHEEL_GROUND_OFFSET_M = 0.2372

TEMPLATE = """<?xml version="1.0"?>
<sdf version="1.9">
  <world name="empty">
    <!-- Generated by tools/generate_ledge_world.py --height {height_m} - see
         src/tap_sim/worlds/ledge_test.sdf for the hand-written 20 cm original
         this is parameterized from. Isolated world: ground_plane + one
         static ledge_pad + departure fillet, nothing else nearby. -->
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-apply-link-wrench-system" name="gz::sim::systems::ApplyLinkWrench"/>
    <gravity>0 0 -9.81</gravity>
    <physics name="default_physics" type="ignored">
      <max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
      <dart><collision_detector>bullet</collision_detector><solver><solver_type>dantzig</solver_type></solver></dart>
    </physics>
    <light name="sun" type="directional">
      <pose>0 0 10 0 0 0</pose><diffuse>0.8 0.8 0.8 1</diffuse>
      <direction>-0.5 0.1 -0.9</direction><cast_shadows>true</cast_shadows>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="ground">
        <collision name="floor">
          <pose>0 0 -0.5 0 0 0</pose><geometry><box><size>20 20 1</size></box></geometry>
          <surface><friction><ode><mu>1</mu><mu2>1</mu2></ode></friction></surface>
        </collision>
        <visual name="floor">
          <pose>0 0 -0.5 0 0 0</pose><geometry><box><size>20 20 1</size></box></geometry>
          <material><ambient>0.55 0.55 0.55 1</ambient><diffuse>0.55 0.55 0.55 1</diffuse></material>
        </visual>
      </link>
    </model>
    <model name="ledge_pad">
      <static>true</static>
      <pose>0 0 {pad_pose_z} 0 0 0</pose>
      <link name="pad">
        <collision name="c"><geometry><box><size>0.9 0.9 {pad_size_z}</size></box></geometry>
          <surface><friction><ode><mu>1.35</mu><mu2>0.08</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><box><size>0.9 0.9 {pad_size_z}</size></box></geometry>
          <material><ambient>0.30 0.42 0.52 1</ambient><diffuse>0.30 0.42 0.52 1</diffuse></material></visual>
      </link>
    </model>
    <model name="ledge_pad_departure_fillet">
      <static>true</static>
      <pose>{fillet_x} 0 {fillet_z} 1.5707963 0 0</pose>
      <link name="fillet">
        <collision name="c"><geometry><cylinder><radius>{fillet_r}</radius><length>0.96</length></cylinder></geometry>
          <surface><friction><ode><mu>1.35</mu><mu2>0.08</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><cylinder><radius>{fillet_r}</radius><length>0.96</length></cylinder></geometry>
          <material><ambient>0.30 0.42 0.52 1</ambient><diffuse>0.30 0.42 0.52 1</diffuse></material></visual>
      </link>
    </model>
  </world>
</sdf>
"""


def generate(height_m: float) -> str:
    pad_size_z = height_m + 0.02
    pad_pose_z = height_m / 2.0 - 0.01
    fillet_z = height_m - FILLET_RADIUS
    fillet_x = PAD_HALF_FOOTPRINT - FILLET_RADIUS
    return TEMPLATE.format(
        height_m=height_m, pad_size_z=pad_size_z, pad_pose_z=pad_pose_z,
        fillet_x=fillet_x, fillet_z=fillet_z, fillet_r=FILLET_RADIUS)


def spawn_z_for(height_m: float) -> float:
    return height_m + STANDARD_WHEEL_GROUND_OFFSET_M


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--height', type=float, required=True, help='ledge height in meters')
    parser.add_argument('--out', type=str, required=True, help='output .sdf path')
    args = parser.parse_args()
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(generate(args.height))
    print(f'wrote {out_path} (height={args.height} m, spawn_z={spawn_z_for(args.height)})')


if __name__ == '__main__':
    main()
