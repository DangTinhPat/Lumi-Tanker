#!/usr/bin/env python3
"""Export conservative body boxes from the adopted GIM CAD collision meshes.

Run after changing the CAD/model. No MuJoCo runtime or contact data is used.
The boxes bound each exposed body component in the native body frame (metres).
"""
import argparse
import hashlib
from pathlib import Path
import struct
import xml.etree.ElementTree as ET


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, default=root / 'src/tap_sim/model/gim_dynamic.xml')
    parser.add_argument('--output', type=Path, default=root / 'src/tap_control/core/include/robot_control/GeneratedBodyEnvelope.hpp')
    args = parser.parse_args()
    tree = ET.parse(args.model)
    meshes = {m.get('name'): m for m in tree.findall('./asset/mesh')}
    rows = []
    digest = hashlib.sha256()
    for geom in tree.findall('./worldbody/body[@name="gim_body"]/geom'):
        if geom.get('contype') != '1':
            continue
        if geom.get('type') != 'mesh' or any(k in geom.attrib for k in ('quat', 'euler', 'axisangle', 'xyaxes', 'zaxis')):
            raise ValueError('Expected unrotated CAD body mesh')
        mesh = meshes[geom.get('mesh')]
        if any(k in mesh.attrib for k in ('refpos', 'refquat')):
            raise ValueError('Mesh reference transforms require explicit handling')
        data = (args.model.parent / mesh.get('file')).read_bytes()
        count = struct.unpack_from('<I', data, 80)[0]
        if len(data) != 84 + 50 * count or count == 0:
            raise ValueError('Expected nonempty binary STL')
        pos = tuple(map(float, geom.get('pos', '0 0 0').split()))
        scale = tuple(map(float, mesh.get('scale', '1 1 1').split()))
        digest.update(data)
        digest.update(repr((geom.get('name'), pos, scale)).encode())
        points = [tuple(v[j] * scale[j] + pos[j] for j in range(3))
                  for i in range(count) for k in range(3)
                  for v in [struct.unpack_from('<3f', data, 84 + 50*i + 12 + 12*k)]]
        # One micrometre outward padding covers decimal serialization.
        lo = [min(p[j] for p in points) - 1e-6 for j in range(3)]
        hi = [max(p[j] for p in points) + 1e-6 for j in range(3)]
        rows.append('    {{' + ', '.join(f'{v:.9f}F' for v in lo) + '}, {' +
                    ', '.join(f'{v:.9f}F' for v in hi) + '}},  // ' + geom.get('name'))
    if not rows:
        raise ValueError('No body contact meshes found')
    args.output.write_text(
        '// Generated by tools/generate_body_envelope.py from GIM STEP mesh exports.\n'
        '// Source: src/tap_sim/model/gim_dynamic.xml, exposed body CAD components.\n'
        f'// Mesh/placement SHA256: {digest.hexdigest()}\n'
        '// Conservative component bounds, not collision geometry added to the sim.\n'
        '#pragma once\n#include <array>\nnamespace robot_control::geometry {\n'
        'struct BodyBox { std::array<float, 3> lo, hi; };\n'
        f'inline constexpr std::array<BodyBox, {len(rows)}> body_envelope{{{{\n' +
        '\n'.join(rows) + '\n}};\n}  // namespace robot_control::geometry\n')


if __name__ == '__main__':
    main()
